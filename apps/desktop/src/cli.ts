import { spawnSync } from "node:child_process";
import { existsSync, lstatSync, readlinkSync } from "node:fs";
import { chmod, mkdir, symlink, unlink, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import {
  agentCommands,
  installMcpConfig,
  MCP_CLIENTS,
  type Exec,
  type McpClient,
} from "@beyland/sprue";
import { CoreError, defineCommand, defaultWorkspaceRoot, type Core } from "@beyland/sprue-core";
import { app, dialog, type BrowserWindow } from "electron";
import { z } from "zod";

/**
 * The bundled `sp` command: a launcher script that runs dist/cli.mjs with this app's runtime
 * (ELECTRON_RUN_AS_NODE), so it needs no Node.js install. Packaged apps ship it in
 * resources/bin; dev runs generate one pointing at the dev build.
 */
export async function launcherPath(appDir: string): Promise<string> {
  if (app.isPackaged)
    return path.join(process.resourcesPath, "bin", process.platform === "win32" ? "sp.cmd" : "sp");
  const file = path.join(appDir, "..", ".dev", "bin", "sp");
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(
    file,
    `#!/usr/bin/env bash
# Dev build of the \`sp\` launcher (generated by src/cli.ts; packaged apps use resources/bin/sp).
export SPRUE_CLI_LAUNCHER=${JSON.stringify(file)}
ELECTRON_RUN_AS_NODE=1 exec ${JSON.stringify(process.execPath)} ${JSON.stringify(path.join(appDir, "cli.mjs"))} "$@"
`,
  );
  await chmod(file, 0o755);
  return file;
}

/** Where "Install 'sp' command in PATH" puts the link. Windows isn't supported yet. */
export function pathLinkTarget(): string | undefined {
  if (process.platform === "darwin") return "/usr/local/bin/sp";
  if (process.platform === "linux") return path.join(os.homedir(), ".local", "bin", "sp");
  return undefined;
}

function linkOf(file: string): string | undefined {
  try {
    return lstatSync(file).isSymbolicLink() ? readlinkSync(file) : undefined;
  } catch {
    return undefined;
  }
}

/** A link we made (to this app's launcher, or another Sprue install's). */
function isSprueLink(target: string | undefined, launcher: string): boolean {
  return Boolean(
    target &&
    (target === launcher ||
      /(Sprue\.app\/Contents\/Resources|[\\/]resources|[\\/]\.dev)[\\/]bin[\\/]sp$/.test(target)),
  );
}

/** Run a shell command as an administrator (macOS shows its password prompt). */
function runAsAdmin(command: string): void {
  const script = `do shell script ${JSON.stringify(command)} with administrator privileges with prompt "Sprue wants to install the 'sp' shell command."`;
  const result = spawnSync("osascript", ["-e", script], { encoding: "utf8" });
  if (result.status !== 0) {
    const message = (result.stderr || "").trim();
    if (/User canceled|-128/.test(message)) throw new CoreError("CONFLICT", "Cancelled.");
    throw new CoreError("INVALID_INPUT", message || "Couldn't change /usr/local/bin.");
  }
}

const quote = (value: string) => `'${value.replace(/'/g, "'\\''")}'`;

async function linkInto(target: string, launcher: string): Promise<void> {
  try {
    await mkdir(path.dirname(target), { recursive: true });
    if (existsSync(target) || linkOf(target)) await unlink(target);
    await symlink(launcher, target);
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (process.platform !== "darwin" || (code !== "EACCES" && code !== "EPERM")) throw error;
    runAsAdmin(
      `mkdir -p ${quote(path.dirname(target))} && ln -sf ${quote(launcher)} ${quote(target)}`,
    );
  }
}

async function unlinkFrom(target: string): Promise<void> {
  try {
    await unlink(target);
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (process.platform !== "darwin" || (code !== "EACCES" && code !== "EPERM")) throw error;
    runAsAdmin(`rm -f ${quote(target)}`);
  }
}

/**
 * Runs a client CLI (`claude`, `codex`) the way a terminal would: apps opened from the Dock
 * don't get the shell's PATH, so go through a login shell.
 */
const loginShellExec: Exec = (command, args) => {
  const result =
    process.platform === "win32"
      ? spawnSync(command, args, { encoding: "utf8", shell: true, timeout: 60_000 })
      : spawnSync(process.env.SHELL || "/bin/zsh", ["-ilc", 'exec "$0" "$@"', command, ...args], {
          encoding: "utf8",
          timeout: 60_000,
        });
  const notFound = result.status === 127 || /command not found/.test(result.stderr ?? "");
  return {
    status: result.status,
    stdout: result.stdout ?? "",
    stderr: result.stderr ?? "",
    error: notFound
      ? Object.assign(new Error(`${command} not found`), { code: "ENOENT" })
      : result.error,
  };
};

/** Internal commands for the desktop app's shell integration (not offered to agents). */
export function cliCommands(options: {
  appDir: string;
  core: () => Core | null;
  window: () => BrowserWindow | null;
}) {
  const showMessage = (message: string, detail?: string, type: "info" | "warning" = "info") => {
    const parent = options.window();
    const box = { type, message, detail, buttons: ["OK"] };
    return parent ? dialog.showMessageBox(parent, box) : dialog.showMessageBox(box);
  };

  const status = defineCommand({
    name: "app.cliStatus",
    title: "sp command status",
    description: "Whether this app can put its `sp` command in PATH, and whether it has.",
    kind: "query",
    internal: true,
    input: z.object({}),
    handler: async () => {
      const target = pathLinkTarget();
      const launcher = await launcherPath(options.appDir);
      return {
        supported: Boolean(target),
        target: target ?? null,
        installed: Boolean(target && isSprueLink(linkOf(target), launcher)),
      };
    },
  });

  const install = defineCommand({
    name: "app.installCli",
    title: "Install 'sp' command in PATH",
    description: "Link this app's `sp` launcher into PATH.",
    kind: "mutation",
    internal: true,
    input: z.object({}),
    handler: async () => {
      const target = pathLinkTarget();
      if (!target) throw new CoreError("INVALID_INPUT", "Not supported on this platform yet.");
      const launcher = await launcherPath(options.appDir);
      const current = linkOf(target);
      if ((current && !isSprueLink(current, launcher)) || (!current && existsSync(target))) {
        const parent = options.window();
        const box = {
          type: "question" as const,
          message: `Replace the existing 'sp' command?`,
          detail: `${target} ${current ? `points to ${current}` : "already exists"}. Sprue will replace it with its own.`,
          buttons: ["Replace", "Cancel"],
          defaultId: 0,
          cancelId: 1,
        };
        const { response } = parent
          ? await dialog.showMessageBox(parent, box)
          : await dialog.showMessageBox(box);
        if (response !== 0) return { installed: false, target };
      }
      try {
        await linkInto(target, launcher);
      } catch (error) {
        if ((error as CoreError).message === "Cancelled.") return { installed: false, target };
        throw error;
      }
      const onPath = (process.env.PATH ?? "").split(path.delimiter).includes(path.dirname(target));
      await showMessage(
        "Shell command 'sp' installed in PATH.",
        process.platform === "linux" && !onPath
          ? `Linked ${target}. Add ${path.dirname(target)} to your PATH if your shell doesn't find it.`
          : `Linked ${target}. Open a new terminal to use it.`,
      );
      return { installed: true, target };
    },
  });

  const uninstall = defineCommand({
    name: "app.uninstallCli",
    title: "Uninstall 'sp' command from PATH",
    description: "Remove the `sp` link this app put in PATH.",
    kind: "mutation",
    internal: true,
    input: z.object({}),
    handler: async () => {
      const target = pathLinkTarget();
      if (!target) throw new CoreError("INVALID_INPUT", "Not supported on this platform yet.");
      const launcher = await launcherPath(options.appDir);
      if (!isSprueLink(linkOf(target), launcher)) {
        await showMessage("Sprue's 'sp' command isn't installed in PATH.", undefined, "warning");
        return { removed: false, target };
      }
      try {
        await unlinkFrom(target);
      } catch (error) {
        if ((error as CoreError).message === "Cancelled.") return { removed: false, target };
        throw error;
      }
      await showMessage("Shell command 'sp' removed from PATH.", `Removed ${target}.`);
      return { removed: true, target };
    },
  });

  /** How this app launches `sp mcp` (its launcher, plus --home for a non-default workspace). */
  const launch = async () => {
    const root = options.core()?.workspace.root;
    const home = root && root !== defaultWorkspaceRoot() ? ["--home", root] : [];
    return { command: await launcherPath(options.appDir), args: ["mcp", ...home] };
  };

  const connect = defineCommand({
    name: "app.connectAgent",
    title: "Connect an agent",
    description: "Add Sprue to an agent's MCP config, launched through this app's `sp`.",
    kind: "mutation",
    internal: true,
    input: z.object({
      client: z.enum(MCP_CLIENTS as [McpClient, ...McpClient[]]),
      force: z.boolean().optional(),
    }),
    handler: async ({ client, force }) =>
      installMcpConfig(client, await launch(), { force, exec: loginShellExec }),
  });

  return [status, install, uninstall, connect, ...agentCommands(launch)];
}
