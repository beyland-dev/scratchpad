import { existsSync } from "node:fs";
import { appendFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { closeBrowser, captureCommands } from "@beyland/sprue-capture";
import {
  Core,
  CoreError,
  defineCommand,
  defaultWorkspaceRoot,
  readUserSettings,
  updateUserSettings,
} from "@beyland/sprue-core";
import { startServer, type RunningServer } from "@beyland/sprue-server";
import { app, BrowserWindow, dialog, shell } from "electron";
import { z } from "zod";
import { cliCommands } from "./cli.ts";

const appDir = path.dirname(fileURLToPath(import.meta.url));
/** App icons from the Settings picker (generated by scripts/generate-icons.py). */
const iconsDir = path.join(appDir, "icons");
const iconFile = (id: string, macos = false) =>
  path.join(iconsDir, `${id}${macos ? "-macos" : ""}.png`);
const knownIcon = (id: string | undefined) =>
  id && /^[a-z0-9-]+$/.test(id) && existsSync(iconFile(id)) ? id : "default";
let currentIcon = knownIcon(readUserSettings().appIcon);
// A separate profile (and single-instance lock), e.g. to try onboarding alongside your own.
if (process.env.SPRUE_USER_DATA) app.setPath("userData", process.env.SPRUE_USER_DATA);
if (process.env.SPRUE_DEBUG_PORT)
  app.commandLine.appendSwitch("remote-debugging-port", process.env.SPRUE_DEBUG_PORT);
let mainWindow: BrowserWindow | null = null;
let core: Core | null = null;
let server: RunningServer | null = null;
let quitting = false;

async function debug(message: string): Promise<void> {
  if (process.env.SPRUE_DEBUG_LOG)
    await appendFile(process.env.SPRUE_DEBUG_LOG, `${message}\n`, "utf8");
}

async function openExternal(url: string): Promise<void> {
  if (/^https?:\/\//.test(url)) await shell.openExternal(url);
}

/** Lets Settings apply a new workspace folder: the app reopens on it. */
const relaunchCommand = defineCommand({
  name: "app.relaunch",
  title: "Restart Sprue",
  description: "Restart the desktop app, e.g. to switch to a new workspace folder.",
  kind: "mutation",
  internal: true,
  input: z.object({}),
  handler: () => {
    // Answer the request first; quitting runs the usual shutdown.
    setTimeout(() => {
      app.relaunch();
      app.quit();
    }, 100);
    return { restarting: true };
  },
});

/** macOS: the Dock (while running; unpackaged runs would otherwise show Electron's icon). Elsewhere: the window and taskbar. */
function applyIcon(id: string): void {
  currentIcon = id;
  if (process.platform === "darwin") app.dock?.setIcon(iconFile(id, true));
  else mainWindow?.setIcon(iconFile(id));
}

const iconCommand = defineCommand({
  name: "app.icon",
  title: "App icon",
  description: "The desktop app icon chosen in Settings.",
  kind: "query",
  internal: true,
  input: z.object({}),
  handler: () => ({ icon: currentIcon, platform: process.platform }),
});

const setIconCommand = defineCommand({
  name: "app.setIcon",
  title: "Set app icon",
  description: "Change the desktop app icon (Dock on macOS, window and taskbar elsewhere).",
  kind: "mutation",
  internal: true,
  input: z.object({ icon: z.string().regex(/^[a-z0-9-]+$/) }),
  handler: async ({ icon }) => {
    if (knownIcon(icon) !== icon) throw new CoreError("NOT_FOUND", `No app icon ${icon}`);
    await updateUserSettings({ appIcon: icon === "default" ? undefined : icon });
    applyIcon(icon);
    return { icon };
  },
});

async function createWindow(): Promise<void> {
  applyIcon(currentIcon);
  await debug("opening core");
  core = await Core.open({
    root: defaultWorkspaceRoot(),
    watch: true,
    commands: [
      ...captureCommands,
      relaunchCommand,
      iconCommand,
      setIconCommand,
      ...cliCommands({ appDir, core: () => core, window: () => mainWindow }),
    ],
  });
  await debug("starting server");
  server = await startServer({
    core,
    host: "127.0.0.1",
    // Stable ports keep the app's origin (and its saved theme, sidebar width, …) across
    // launches; the server moves to the next free port if one is taken.
    port: 7430,
    sandboxPort: 7450,
    strictPort: false,
    webRoot: path.join(appDir, "web"),
  });
  await debug(`server started at ${server.url}`);

  const window = new BrowserWindow({
    width: 1440,
    height: 960,
    minWidth: 880,
    minHeight: 600,
    show: false,
    backgroundColor: "#f7f7f8",
    title: "Sprue",
    icon: iconFile(currentIcon),
    titleBarStyle: process.platform === "darwin" ? "hiddenInset" : "hidden",
    ...(process.platform === "darwin"
      ? { trafficLightPosition: { x: 14, y: 12 } }
      : {
          titleBarOverlay: {
            color: "#00000000",
            symbolColor: "#77777f",
            height: 38,
          },
        }),
    webPreferences: {
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });
  mainWindow = window;
  const appOrigin = new URL(server.url).origin;
  window.webContents.setWindowOpenHandler(({ url }) => {
    if (url === "about:blank" || new URL(url).origin === appOrigin) return { action: "allow" };
    void openExternal(url);
    return { action: "deny" };
  });
  window.webContents.on("will-navigate", (event, url) => {
    if (new URL(url).origin === appOrigin) return;
    event.preventDefault();
    void openExternal(url);
  });
  window.once("ready-to-show", () => window.show());
  window.on("closed", () => {
    if (mainWindow === window) mainWindow = null;
  });
  const url = new URL(server.url);
  url.searchParams.set("desktop", process.platform);
  await window.loadURL(url.href);
  await debug("window loaded");
}

async function shutdown(): Promise<void> {
  await Promise.all([server?.close(), closeBrowser()]);
  server = null;
  await core?.close();
  core = null;
}

async function reportStartupError(error: unknown): Promise<void> {
  const message = error instanceof Error ? (error.stack ?? error.message) : String(error);
  console.error("Sprue could not start", error);
  const logs = app.getPath("logs");
  await mkdir(logs, { recursive: true });
  await writeFile(path.join(logs, "startup-error.log"), `${message}\n`, "utf8");
  dialog.showErrorBox("Sprue could not start", message);
}

const lock = app.requestSingleInstanceLock();
if (!lock) app.quit();
else {
  void debug("single-instance lock acquired");
  app.on("second-instance", () => {
    if (!mainWindow) return;
    if (mainWindow.isMinimized()) mainWindow.restore();
    mainWindow.focus();
  });
  app
    .whenReady()
    .then(createWindow)
    .catch(async (error: unknown) => {
      await reportStartupError(error);
      await shutdown();
      app.quit();
    });
  app.on("activate", () => {
    if (!mainWindow && app.isReady()) void createWindow();
  });
  app.on("window-all-closed", () => {
    if (process.platform !== "darwin") app.quit();
  });
  app.on("before-quit", (event) => {
    if (quitting || (!server && !core)) return;
    event.preventDefault();
    quitting = true;
    void shutdown().finally(() => app.quit());
  });
}
