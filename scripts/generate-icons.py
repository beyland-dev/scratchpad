#!/usr/bin/env python3
"""Generate every app icon variant from the source art in assets/icons/*.png.

Source art is 1024x1024 and may be full-bleed or have dark corners; every output gets
transparent rounded corners. Also writes apps/web/src/app-icons.ts, the list the Settings
picker shows. Run after adding, changing, or removing source art:

    python3 -m pip install pillow
    python3 scripts/generate-icons.py
"""

import shutil
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "assets" / "icons"
WEB = ROOT / "apps" / "web" / "public"
DESKTOP = ROOT / "apps" / "desktop" / "resources"
ICON_LIST = ROOT / "apps" / "web" / "src" / "app-icons.ts"
DEFAULT = "default"
# Picker order; icons not listed follow alphabetically.
ORDER = ["default", "blue", "green", "orange", "chrome", "wood", "pearl", "holographic"]
# Names that aren't just the file name in title case.
LABELS = {"default": "Classic", "holographic": "Holo"}
SUPERSAMPLE = 4


def rounded_mask(size: int, radius: int) -> Image.Image:
    big = Image.new("L", (size * SUPERSAMPLE, size * SUPERSAMPLE), 0)
    ImageDraw.Draw(big).rounded_rectangle(
        (0, 0, size * SUPERSAMPLE - 1, size * SUPERSAMPLE - 1), radius * SUPERSAMPLE, fill=255
    )
    return big.resize((size, size), Image.LANCZOS)


def full_bleed(src: Image.Image, size: int) -> Image.Image:
    """The whole canvas with rounded, transparent corners (web, Windows, Linux)."""
    out = src.resize((size, size), Image.LANCZOS)
    out.putalpha(rounded_mask(size, round(size * 0.225)))
    return out


def macos_grid(src: Image.Image, size: int) -> Image.Image:
    """Apple's icon grid: an 824/1024 rounded body centered on a transparent canvas, with a shadow."""
    body_size = round(size * 824 / 1024)
    inset = (size - body_size) // 2
    mask = rounded_mask(body_size, round(body_size * 0.225))
    body = src.resize((body_size, body_size), Image.LANCZOS)
    body.putalpha(mask)
    shadow_alpha = Image.new("L", (size, size), 0)
    shadow_alpha.paste(mask.point(lambda a: int(a * 0.35)), (inset, inset + round(size * 0.012)))
    shadow = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    shadow.putalpha(shadow_alpha.filter(ImageFilter.GaussianBlur(size * 0.014)))
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.alpha_composite(shadow)
    canvas.alpha_composite(body, (inset, inset))
    return canvas


def save(image: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)


def label(stem: str) -> str:
    return LABELS.get(stem) or " ".join(word.capitalize() for word in stem.split("-"))


def write_icon_list(stems: list[str]) -> None:
    entries = "".join(f'  {{ id: "{stem}", label: "{label(stem)}" }},\n' for stem in stems)
    ICON_LIST.write_text(
        "// Generated by scripts/generate-icons.py from assets/icons/*.png. Don't edit by hand.\n"
        "export const APP_ICON_LIST = [\n" + entries + "] as const;\n"
    )


def main() -> None:
    sources = sorted(SOURCES.glob("*.png"))
    if not any(p.stem == DEFAULT for p in sources):
        raise SystemExit(f"Missing {SOURCES / (DEFAULT + '.png')}")
    # Start clean, so removed art doesn't linger in the builds.
    for folder in (WEB / "icons", DESKTOP / "icons"):
        shutil.rmtree(folder, ignore_errors=True)
    sources.sort(key=lambda p: (ORDER.index(p.stem) if p.stem in ORDER else len(ORDER), p.stem))
    write_icon_list([p.stem for p in sources])
    for path in sources:
        src = Image.open(path).convert("RGBA")
        save(full_bleed(src, 128), WEB / "icons" / f"{path.stem}.png")
        save(full_bleed(src, 512), DESKTOP / "icons" / f"{path.stem}.png")
        save(macos_grid(src, 512), DESKTOP / "icons" / f"{path.stem}-macos.png")
        if path.stem == DEFAULT:
            save(full_bleed(src, 128), WEB / "favicon.png")
            save(full_bleed(src, 1024), DESKTOP / "app-icon.png")
            save(macos_grid(src, 1024), DESKTOP / "app-icon-macos.png")
        print(f"✓ {path.stem}")


if __name__ == "__main__":
    main()
